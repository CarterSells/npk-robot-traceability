import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { readFileSync } from 'node:fs';

test('engineer JSON and CSV flow reuses mappings, compares custom fields, preserves corrections and exports', async ({ page }) => {
  const writes: string[]=[];
  page.on('request',r=>{if(r.method()!=='GET'&&!r.url().includes('__nextjs'))writes.push(r.url());});
  await page.goto('/workspace/');
  const robot=page.getByRole('form',{name:'Add a robot'});
  await robot.getByLabel('Robot ID',{exact:false}).fill('custom-arm');
  await robot.getByLabel('Robot name').fill('Synthetic custom arm');
  await robot.getByLabel('Task / cell').fill('Synthetic component test');
  await robot.getByRole('button',{name:'Add robot',exact:true}).click();
  await page.getByText('Import engineer metadata · JSON / CSV',{exact:true}).click();
  const metadata=page.getByRole('group',{name:'Engineer metadata import',exact:true});
  const upload=async(n:number,extra=false)=>metadata.getByLabel('Engineer metadata file').setInputFiles({name:'synthetic.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({arm:{torque:{value:n,unit:'Nm'}},leg:{enabled:true},secret:'excluded-private-example',...(extra?{newField:999}:{})}))});
  await upload(12);
  await expect(metadata.getByRole('button',{name:'Add approved snapshot'})).toBeDisabled();
  await expect(metadata.getByRole('checkbox',{name:'/secret · blocked sensitive field'})).toBeDisabled();
  await metadata.getByRole('checkbox',{name:'/arm/torque/value',exact:true}).check();
  await metadata.getByRole('checkbox',{name:'/leg/enabled',exact:true}).check();
  await metadata.getByLabel('Import author').fill('Synthetic engineer');
  await metadata.getByLabel('Metadata observed at (UTC)',{exact:false}).fill('2026-10-10T10:00:00Z');
  await expect(metadata.getByText('12 Nm',{exact:false})).toBeVisible();
  for(const width of [320,768,1440]) {
    await page.setViewportSize({width,height:900});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  }
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/custom-metadata-mobile.png',fullPage:true});
  await page.setViewportSize({width:1280,height:900});
  await metadata.getByRole('button',{name:'Add approved snapshot'}).click();
  await expect(page.getByRole('status')).toContainText('Approved metadata snapshot added');
  await expect(page.getByRole('button',{name:'Record',exact:true})).toHaveAttribute('aria-pressed','true');
  const revision=page.getByRole('form',{name:'Record a test run',exact:true}).getByRole('combobox',{name:'Exact snapshot revision',exact:true});
  const first=await revision.inputValue();
  const recordRun=async(id:string,snapshot:string,outcome:string)=>{
    await page.getByRole('button',{name:'Record',exact:true}).click();
    const form=page.getByRole('form',{name:'Record a test run',exact:true});
    if(!(await form.isVisible()))await page.getByText('Record a test run',{exact:true}).click();
    await form.getByLabel('Run ID',{exact:true}).fill(id);
    await expect(form.getByRole('combobox',{name:'Exact snapshot revision',exact:true})).toHaveValue(snapshot);
    await form.getByLabel('Run time (UTC)').fill(id==='first'?'2026-10-10T10:05:00Z':'2026-10-10T11:05:00Z');
    await form.getByRole('combobox',{name:'Outcome',exact:true}).selectOption(outcome);
    await form.getByRole('button',{name:'Record run',exact:true}).click();
    await expect(page.getByRole('status')).toContainText('Run recorded');
  };
  await recordRun('first',first,'success');
  await upload(18,true);
  await expect(metadata.getByText('Reusing Engineer metadata.',{exact:false})).toBeVisible();
  await metadata.getByRole('button',{name:'Add approved snapshot'}).click();
  const second=await revision.inputValue();
  await recordRun('second',second,'failure');
  await page.getByRole('combobox',{name:'Successful baseline',exact:true}).selectOption('first');
  const comparison=page.getByRole('region',{name:'Run comparison'});
  await expect(comparison.getByRole('row').filter({hasText:'torque'})).toContainText('Changed');
  await expect(comparison).toContainText('12 Nm');await expect(comparison).toContainText('18 Nm');
  await expect(comparison).not.toContainText('newField');
  await page.getByRole('button',{name:'History',exact:true}).click();
  await page.getByText('Correct a recorded field',{exact:true}).click();
  const correction=page.getByRole('form',{name:'Correct a field'});
  await correction.getByRole('combobox',{name:'Field to correct',exact:true}).selectOption({label:'arm / torque (Nm)'});
  await correction.getByRole('textbox',{name:/^Field value/}).fill('19');
  await correction.getByLabel('Correction author').fill('Synthetic reviewer');
  await correction.getByLabel('Reason for correction').fill('Correct synthetic transcription');
  await correction.getByRole('button',{name:'Append correction'}).click();
  await expect(page.getByRole('status')).toContainText('Correction appended');
  const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Export JSON',exact:true}).click();
  const download=await pending, exported=readFileSync((await download.path())!,'utf8'), bundle=JSON.parse(exported);
  expect(bundle.version).toBe(2);expect(bundle.mappings).toHaveLength(1);
  expect(bundle.records.runs.every((r:{snapshotRevision:number})=>r.snapshotRevision===1)).toBe(true);
  expect(exported).not.toContain('excluded-private-example');expect(exported).not.toContain('newField');
  await page.getByRole('button',{name:'Clear workspace',exact:true}).click();
  await page.getByLabel('Import JSON',{exact:true}).setInputFiles({name:'workspace.json',mimeType:'application/json',buffer:Buffer.from(exported)});
  await page.getByText('Import engineer metadata · JSON / CSV',{exact:true}).click();
  await metadata.getByLabel('Engineer metadata file').setInputFiles({name:'synthetic.csv',mimeType:'text/csv',buffer:Buffer.from('Torque [Nm]\n20\n21\n')});
  await metadata.getByRole('checkbox',{name:'/Torque [Nm]',exact:true}).check();
  await metadata.getByLabel('CSV data row').selectOption('1');
  await metadata.getByLabel('Import author').fill('Synthetic CSV engineer');
  await expect(metadata.getByText('21 Nm',{exact:false})).toBeVisible();
  await metadata.getByRole('button',{name:'Add approved snapshot'}).click();
  await expect(page.getByRole('status')).toContainText('Approved metadata snapshot added');
  expect(writes).toEqual([]);
});
